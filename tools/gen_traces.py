#!/usr/bin/env python3
"""Generate the synthetic sensor traces used by crates/core/tests/scenarios.rs.

These are NOT recordings from a phone (no device was available when they
were made). They come from a simple, documented physical model so the
state-machine tests have realistic dynamics:

* device pose = in-plane roll `a` (orientation angle, deg; 90 = phone turned
  counter-clockwise) and tilt `t` (deg between screen plane and horizontal);
  the gravity "up" vector in the device frame is
  9.81 * (cos t * sin a, cos t * cos a, sin t)
* rotations follow a minimum-jerk profile s(u) = 10u^3 - 15u^4 + 6u^5, the
  standard model for voluntary human arm movements;
* physiological hand tremor: ~0.35 deg at 9 Hz plus a slow random walk;
* sensor noise: N(0, 0.03 m/s^2) for TYPE_GRAVITY,
  N(0, 0.15) plus motion-correlated linear acceleration for raw
  accelerometer traces;
* sample period 20 ms (SENSOR_DELAY_GAME) with +-2 ms jitter.

Real traces from a device can be captured with scripts/record_trace.sh (debug
builds log gravity samples, never camera data) and dropped into the same
directory; the format is identical.

Usage: python3 tools/gen_traces.py crates/core/tests/traces
"""
import math
import os
import random
import sys

G = 9.81


def min_jerk(u):
    u = min(max(u, 0.0), 1.0)
    return 10 * u**3 - 15 * u**4 + 6 * u**5


class Segment:
    """Move (a, t) from the previous pose to (a1, t1) over dur_ms (0 = hold)."""

    def __init__(self, dur_ms, a1=None, t1=None):
        self.dur_ms, self.a1, self.t1 = dur_ms, a1, t1


def synth(segments, a0, t0, seed, sensor="gravity", extra_noise=0.0, bob=None):
    rng = random.Random(seed)
    out = []
    a, t = a0, t0
    time = 0.0
    walk_a = 0.0
    tremor_phase = rng.uniform(0, 2 * math.pi)
    for seg in segments:
        a_start, t_start = a, t
        a_end = a if seg.a1 is None else seg.a1
        t_end = t if seg.t1 is None else seg.t1
        seg_start = time
        while time < seg_start + seg.dur_ms:
            u = (time - seg_start) / seg.dur_ms if seg.dur_ms > 0 else 1.0
            s = min_jerk(u)
            a = a_start + (a_end - a_start) * s
            t = t_start + (t_end - t_start) * s
            walk_a += rng.gauss(0, 0.05)
            walk_a *= 0.995
            tremor = 0.35 * math.sin(2 * math.pi * 9.0 * time / 1000.0 + tremor_phase)
            aa = math.radians(a + tremor + walk_a)
            tt = math.radians(t)
            g = [G * math.cos(tt) * math.sin(aa), G * math.cos(tt) * math.cos(aa), G * math.sin(tt)]
            sigma = 0.03 if sensor == "gravity" else 0.15
            sigma += extra_noise
            # Motion-correlated linear acceleration (accelerometer only):
            # proportional to the angular acceleration of the min-jerk profile.
            if sensor == "accelerometer" and seg.dur_ms > 0 and 0 < u < 1:
                acc = (60 * u - 180 * u**2 + 120 * u**3) * (a_end - a_start) / 90.0
                g[0] += 0.4 * acc
            if bob is not None:  # walking: vertical bob along device y and z
                amp, hz = bob
                ph = math.sin(2 * math.pi * hz * time / 1000.0)
                g[1] += amp * ph
                g[2] += 0.5 * amp * ph
            g = [v + rng.gauss(0, sigma) for v in g]
            out.append((int(round(time)), g))
            time += 20.0 + rng.uniform(-2.0, 2.0)
        a, t = a_end, t_end
    return out


def write(path, meta, samples):
    with open(path, "w") as f:
        f.write("# SYNTHETIC trace generated by tools/gen_traces.py (not a device recording)\n")
        for k, v in meta.items():
            f.write(f"# {k}: {v}\n")
        f.write("t_ms,gx,gy,gz\n")
        for t, g in samples:
            f.write(f"{t},{g[0]:.4f},{g[1]:.4f},{g[2]:.4f}\n")


def scenarios():
    S = Segment
    return {
        # Sitting, turning the phone counter-clockwise into landscape.
        "rotate_ccw_sitting": (dict(sensor="gravity", head="RotatedRight", expect="R90"),
                               synth([S(1000), S(450, a1=90, t1=20), S(1500)], 0, 35, 1)),
        # Same with the raw accelerometer (no TYPE_GRAVITY sensor).
        "rotate_ccw_sitting_accel": (dict(sensor="accelerometer", head="RotatedRight", expect="R90"),
                                     synth([S(1000), S(450, a1=90, t1=20), S(1500)], 0, 35, 2, sensor="accelerometer")),
        # Turning clockwise.
        "rotate_cw_sitting": (dict(sensor="gravity", head="RotatedLeft", expect="R270"),
                              synth([S(1000), S(500, a1=-90, t1=25), S(1500)], 0, 35, 3)),
        # Lying down on the left side, phone stays portrait relative to the face.
        "lie_down_left": (dict(sensor="gravity", head="Upright", expect="R0"),
                          synth([S(1000), S(1100, a1=88, t1=15), S(2000)], 0, 35, 4)),
        # Lying down on the right side.
        "lie_down_right": (dict(sensor="gravity", head="Upright", expect="R0"),
                           synth([S(1000), S(1100, a1=-85, t1=20), S(2000)], 0, 35, 5)),
        # Lie down left, stay, sit up again.
        "lie_down_then_sit_up": (dict(sensor="gravity", head="Upright", expect="R0"),
                                 synth([S(800), S(1100, a1=88, t1=15), S(2500), S(900, a1=0, t1=35), S(1500)], 0, 35, 6)),
        # Start tilting, change your mind, come back.
        "tilt_and_return": (dict(sensor="gravity", head="Upright", expect="R0"),
                            synth([S(800), S(300, a1=35), S(300, a1=0), S(1500)], 0, 35, 7)),
        # Small wobble while reading.
        "small_drift": (dict(sensor="gravity", head="Upright", expect="R0"),
                        synth([S(600), S(700, a1=8), S(700, a1=-6), S(700, a1=5), S(700, a1=0), S(800)], 0, 35, 8)),
        # Pick the phone up from a table into portrait.
        "pickup_from_table": (dict(sensor="gravity", head="Upright", expect="R0"),
                              synth([S(1000), S(700, t1=40), S(1500)], 2, 88, 9)),
        # Spinning the phone while it lies flat on a table.
        "flat_spin": (dict(sensor="gravity", head="NoFace", expect="R0"),
                      synth([S(800), S(800, a1=95), S(800, a1=180), S(1200)], 0, 86, 10)),
        # Oscillating across 45 degrees (worst case for flapping).
        "flap_45": (dict(sensor="gravity", head="follow", expect="any"),
                    synth([S(500)] + [S(400, a1=(62 if i % 2 == 0 else 28)) for i in range(20)] + [S(500)], 28, 30, 11)),
        # Walking with the phone in portrait.
        "walking_portrait": (dict(sensor="accelerometer", head="Upright", expect="R0"),
                             synth([S(6000)], 0, 30, 12, sensor="accelerometer", extra_noise=0.25, bob=(1.2, 1.9))),
        # Turning the phone upside down.
        "upside_down": (dict(sensor="gravity", head="follow", expect="R180"),
                        synth([S(800), S(700, a1=180, t1=30), S(1500)], 0, 35, 13)),
        # Very slow rotation into landscape (never looks like an onset).
        "slow_rotate": (dict(sensor="gravity", head="RotatedRight", expect="R90"),
                        synth([S(800), S(6000, a1=90, t1=25), S(1500)], 0, 35, 14)),
        # Long continuous fidgeting that never settles (settle timeout).
        "never_settles": (dict(sensor="gravity", head="Upright", expect="R0"),
                          synth([S(600)] + [S(160, a1=(30 if i % 2 == 0 else 8)) for i in range(14)] + [S(300, a1=0), S(1000)], 0, 35, 15)),
    }


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "crates/core/tests/traces"
    os.makedirs(out_dir, exist_ok=True)
    for name, (meta, samples) in scenarios().items():
        write(os.path.join(out_dir, name + ".csv"), dict(scenario=name, **meta), samples)
        print(f"{name}: {len(samples)} samples")


if __name__ == "__main__":
    main()
