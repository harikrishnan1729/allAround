"""Renders reports/metrics.json as Markdown (reports/EVALUATION.md)."""
from .labels import NAMES


def _pct(v):
    return "–" if v is None else f"{100 * v:.1f}%"


def write_markdown(r, path):
    L = []
    L.append("# FaceTilt orientation classifier — evaluation\n")
    L.append("Generated by `python -m facetilt.train`. Test faces: FairFace **validation** split "
             f"({r['test_faces']} images, never used for training), each rendered through the camera "
             "simulator and evaluated at all 4 rotations; no-face samples come from held-out scikit-image "
             "photos, FairFace validation backgrounds and procedural scenes.\n")
    L.append(f"* Parameters: **{r['params']:,}**")
    L.append(f"* Model size: fp32 {r['fp32_bytes'] / 1024:.1f} KB, **int8 {r['int8_bytes'] / 1024:.1f} KB**")
    L.append(f"* Training samples: {r['train_samples']:,}")
    L.append(f"* Best validation accuracy (PyTorch fp32): {_pct(r['val_accuracy_torch'])}\n")

    L.append("## Accuracy per lighting condition (fp32 vs int8)\n")
    L.append("| Condition | fp32 acc | int8 acc | int8 face coverage @0.7 | int8 precision when trusted | "
             "int8 confident-wrong (faces) | int8 no-face trusted |")
    L.append("|---|---|---|---|---|---|---|")
    for cond, res in r["conditions"].items():
        a, b = res["fp32"], res["int8"]
        L.append(f"| {cond} | {_pct(a['accuracy'])} | {_pct(b['accuracy'])} | {_pct(b['face_coverage'])} | "
                 f"{_pct(b['accepted_precision'])} | {_pct(b['confident_wrong_rate_faces'])} | "
                 f"{_pct(b['nonface_accepted_rate'])} |")
    L.append("")
    L.append("*Coverage* = share of face frames the app trusts (confidence ≥ 0.7 and not no-face); the rest "
             "fall back to gravity (standard auto-rotate). *Confident-wrong* is the harmful case: a face frame "
             "trusted with the wrong orientation.\n")

    L.append("## Accuracy per class (int8, random lighting)\n")
    L.append("| Class | fp32 | int8 |")
    L.append("|---|---|---|")
    rnd = r["conditions"]["random"]
    for n in NAMES:
        L.append(f"| {n} | {_pct(rnd['fp32']['per_class'][n])} | {_pct(rnd['int8']['per_class'][n])} |")
    L.append("")
    L.append("## Confusion matrix (int8, random lighting; rows = truth)\n")
    L.append("| truth \\ pred | " + " | ".join(NAMES) + " |")
    L.append("|---" * (len(NAMES) + 1) + "|")
    for n, row in zip(NAMES, rnd["int8"]["confusion"]):
        L.append(f"| {n} | " + " | ".join(str(v) for v in row) + " |")
    L.append("")
    if r.get("groups"):
        L.append("## Face-sample accuracy by FairFace annotation (int8, random lighting)\n")
        L.append("FairFace's perceived race/gender labels are used *only* to audit for performance gaps; "
                 "the model never sees them and cannot output them.\n")
        for key, groups in r["groups"].items():
            L.append(f"| {key} | n | accuracy |")
            L.append("|---|---|---|")
            for g, v in groups.items():
                L.append(f"| {g} | {v['n']} | {_pct(v['accuracy'])} |")
            L.append("")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
